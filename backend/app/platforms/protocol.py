from typing import Protocol, Any


class JobPlatformAdapter(Protocol):
    platform: str

    async def authenticate(self) -> dict[str, Any]: ...
    async def search_jobs(self, query: dict[str, Any]) -> list[dict[str, Any]]: ...
    async def get_job_details(self, platform_job_id: str) -> dict[str, Any]: ...
    def normalize_job(self, raw: dict[str, Any]) -> dict[str, Any]: ...
    async def detect_application_type(self, job: dict[str, Any]) -> str: ...
    async def get_application_form(self, job: dict[str, Any]) -> list[dict[str, Any]]: ...
    async def fill_application_form(self, fields: list[dict[str, Any]], answers: dict[str, Any]) -> dict[str, Any]: ...
    async def upload_resume(self, application: dict[str, Any], resume_path: str) -> dict[str, Any]: ...
    async def submit_application(self, application: dict[str, Any]) -> dict[str, Any]: ...
    async def get_application_status(self, application_id: str) -> dict[str, Any]: ...
    async def logout(self) -> None: ...
    async def health_check(self) -> dict[str, Any]: ...
